/// Haftanın oyunu: her pazartesi (UTC) bir sonrakine geçer.
int weekIndex(DateTime now) {
  final days = now.toUtc().millisecondsSinceEpoch ~/ Duration.millisecondsPerDay;
  return (days + 3) ~/ 7; // 1 Ocak 1970 perşembeydi; haftalar pazartesi başlar.
}
